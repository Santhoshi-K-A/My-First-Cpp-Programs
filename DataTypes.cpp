#include <iostream>
#include <string>

using namespace std;

int main()
{
    // Integer
    int age;
    cout << "Enter your age: ";
    cin >> age;
    cout << "Your age is: " << age << endl;

    // Float
    float marks;
    cout << "Enter your marks: ";
    cin >> marks;
    cout << "Your marks are: " << marks << endl;

    // Boolean
    bool isRaining = true;
    cout << "Is it raining? " << isRaining << endl;

    // String
    string greeting = "Hi";
    cout << greeting << endl;

    return 0;
}
